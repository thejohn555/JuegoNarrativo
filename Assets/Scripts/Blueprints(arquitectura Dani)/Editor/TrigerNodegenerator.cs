using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Blueprints_arquitectura_Dani_.Runtime.Managers;
using UnityEditor;
using UnityEngine;

namespace Blueprints_arquitectura_Dani_.Editor.Blueprints_arquitectura_Dani_.Editor
{
    //rehacer esta clase 
    public class TrigerNodegenerator
    {
        const string OutputPath = "Assets/Blueprints/Editor/Nodes/Generated/TriggerNodes.cs";

        [MenuItem("Blueprints/Generar nodos de trigger")]
        static void GenerateFromScene()
        {
            var manager = Object.FindFirstObjectByType<BlueprintDictionaryManager>();
            if (manager == null)
            {
                Debug.LogWarning("No hay BlueprintDictionaryManager en la escena");
                return;
            }

            var names = manager.triggerList
                .Where(g => g != null)
                .Select(g => g.name);

            Generate(names);
        }

        public static void Generate(IEnumerable<string> names)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> No editar a mano.");
            sb.AppendLine("using System;");
            sb.AppendLine("namespace Blueprints_arquitectura_Dani_.Editor");
            sb.AppendLine("{");

            var used = new HashSet<string>();
            foreach (var name in names.Where(n => !string.IsNullOrWhiteSpace(n)).Distinct())
            {
                string id = ToIdentifier(name);
                if (!used.Add(id)) continue;

                sb.AppendLine("    [Serializable]");
                sb.AppendLine($"    public class OnTriggerEnter_{id} : TriggerEnterNodeBase");
                sb.AppendLine($"    {{ public override string TriggerKey => \"{name}\"; }}");
            }
            sb.AppendLine("}");

            string content = sb.ToString();
            if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == content)
            {
                Debug.Log("[TriggerNodes] Sin cambios");
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
            File.WriteAllText(OutputPath, content);
            AssetDatabase.Refresh();
            Debug.Log($"[TriggerNodes] Generadas {used.Count} clases");
        }

        static string ToIdentifier(string name)
        {
            var sb = new StringBuilder();
            foreach (char c in name)
                sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            return sb.ToString();
        }
    }
}